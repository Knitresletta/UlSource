#!/usr/bin/env python3
"""Build NearbyData.lua: the vendor-sold items class spells consume, and ammo.

Nearby.lua answers "where is the nearest vendor with my class's reagents"
(hunters: ammo for the equipped weapon) from the trainers and vendors this
account has visited. What makes a merchant a reagent vendor is whether its
window holds one of these items, so the item lists are shipped; where the
vendors stand is learned in play, nothing is shipped for that.

Forever sources only (Jonatan, 06.11.2026): the lists come from the Forever
client's own data as wago.tools exports it, never from vanilla databases.

  --wago DIR     CSV exports for the Forever build from
                 https://wago.tools/db2/<Table>/csv?build=<build>:
                 SkillLine, SkillLineAbility, SpellReagents, Item, ItemSparse.

Usage:
    python3 -I tools/build_nearby.py --wago /path/csvdir --build 1.60.1.70790 -o NearbyData.lua

Reagents: every item a spell on a class's skill lines (SkillLine category 7,
the specialisations) lists in SpellReagents, kept when the client gives it
a buy price (a vendor sells it; Soul Shards have none). Ammo: Item class 6,
subclass 2 (arrows) or 3 (bullets), with a buy price, with its item level
so the best one a vendor sells can be named.
"""
import argparse
import csv
import datetime
import sys
from collections import defaultdict

# Specialisation skill line name -> class token, as the Forever client names them.
SPEC_CLASS = {
    "Arms": "WARRIOR", "Fury": "WARRIOR", "Protection": None,   # Protection is Warrior 257 and Paladin 267
    "Holy": None,                                              # Holy is Priest 56 and Paladin 594
    "Retribution": "PALADIN",
    "Beast Mastery": "HUNTER", "Survival": "HUNTER", "Marksmanship": "HUNTER",
    "Combat": "ROGUE", "Subtlety": "ROGUE", "Assassination": "ROGUE",
    "Shadow Magic": "PRIEST", "Discipline": "PRIEST",
    "Enhancement": "SHAMAN", "Elemental Combat": "SHAMAN",
    "Restoration": None,                                       # Shaman 374 and Druid 573
    "Frost": "MAGE", "Fire": "MAGE", "Arcane": "MAGE",
    "Demonology": "WARLOCK", "Affliction": "WARLOCK", "Destruction": "WARLOCK",
    "Feral Combat": "DRUID", "Balance": "DRUID",
}
# The shared names, by skill line ID.
SPEC_CLASS_BY_ID = {257: "WARRIOR", 267: "PALADIN", 56: "PRIEST", 594: "PALADIN", 374: "SHAMAN", 573: "DRUID"}

AMMO_CLASS, ARROW, BULLET = 6, 2, 3


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rows(d, table):
    with open(f"{d}/{table}.csv", encoding="utf-8", newline="") as f:
        yield from csv.DictReader(f)


def class_lines(d):
    out = {}
    for r in rows(d, "SkillLine"):
        if r["CategoryID"] != "7":
            continue
        sid, name = int(r["ID"]), r["DisplayName_lang"]
        cls = SPEC_CLASS_BY_ID.get(sid) or SPEC_CLASS.get(name)
        if cls:
            out[sid] = cls
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--wago", required=True, help="directory with the wago.tools CSV exports")
    ap.add_argument("--build", default="unknown build")
    ap.add_argument("-o", "--out", default="NearbyData.lua")
    a = ap.parse_args()
    d = a.wago

    lines = class_lines(d)
    spell_class = {}
    for r in rows(d, "SkillLineAbility"):
        cls = lines.get(int(r["SkillLine"]))
        if cls:
            spell_class.setdefault(int(r["Spell"]), set()).add(cls)
    reagent_classes = defaultdict(set)
    for r in rows(d, "SpellReagents"):
        classes = spell_class.get(int(r["SpellID"]))
        if not classes:
            continue
        for i in range(8):
            item = int(r[f"Reagent_{i}"] or 0)
            if item > 0:
                reagent_classes[item] |= classes
    kind = {}
    for r in rows(d, "Item"):
        kind[int(r["ID"])] = (int(r["ClassID"]), int(r["SubclassID"]))
    reagents, ammo = {}, {}
    for r in rows(d, "ItemSparse"):
        iid = int(r["ID"])
        buy = int(r["BuyPrice"] or 0)
        name = r["Display_lang"].strip()
        if buy <= 0 or not name:
            continue
        if iid in reagent_classes:
            reagents[iid] = (sorted(reagent_classes[iid]), name)
        cls, sub = kind.get(iid, (None, None))
        if cls == AMMO_CLASS and sub in (ARROW, BULLET):
            ammo[iid] = (sub, int(r["ItemLevel"] or 0), name)

    with open(a.out, "w", encoding="utf-8") as out:
        out.write("-- Generated by tools/build_nearby.py on %s from the Forever client's own\n"
                  "-- data (wago.tools DB2 exports, build %s). Do not edit by hand.\n"
                  "-- Forever sources only: nothing here comes from vanilla databases, and no\n"
                  "-- positions are shipped; trainers and vendors are learned on a visit.\n"
                  "--\n"
                  "-- reagents: item ID -> { class tokens separated by spaces, name }\n"
                  "-- ammo:     item ID -> { subclass (2 arrows, 3 bullets), item level, name }\n\n"
                  % (datetime.date.today().isoformat(), a.build))
        out.write("UlSource.NearbyData = {\n")
        out.write("reagents = {\n")
        for iid in sorted(reagents):
            classes, name = reagents[iid]
            out.write("[%d]={%s,%s},\n" % (iid, lua_string(" ".join(classes)), lua_string(name)))
        out.write("},\n")
        out.write("ammo = {\n")
        for iid in sorted(ammo):
            sub, level, name = ammo[iid]
            out.write("[%d]={%d,%d,%s},\n" % (iid, sub, level, lua_string(name)))
        out.write("},\n}\n")
    print("reagents: %d items; ammo: %d items; class lines: %d" % (len(reagents), len(ammo), len(lines)), file=sys.stderr)
    for iid in sorted(reagents):
        print("  ", iid, reagents[iid], file=sys.stderr)


if __name__ == "__main__":
    main()
