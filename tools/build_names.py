#!/usr/bin/env python3
"""Build NameData.lua: NPC ID -> name and game object ID -> name.

A loot source on Forever is a GUID with the NPC or object ID in it, and
nothing else. Inside instances the client hides unit names from addons
(secret values), so the addon ships a name table and learns the rest in
play. The names are not in the client files (they come from the server),
so the table is built from a server database:

  --vmangos DB   The vmangos world database as SQLite (mangos.sqlite from
                 the db-sqlite-*.zip on the vmangos/core GitHub release
                 tagged db_latest). Vanilla 1.12. Forever's old creatures
                 and nodes keep their 1.12 IDs (checked against the probe
                 data 15.10.2026: 4436 Razorfen Quilguard, 1621 Briarthorn,
                 19861 Henrig Lonebrow's Journal). Forever-new ones are not
                 here and stay unnamed until learned.

Usage:
    python3 -I tools/build_names.py --vmangos /path/mangos.sqlite -o NameData.lua

Creatures: every entry, newest patch row wins. Objects: only types that can
be looted, chests and nodes (type 3, which includes herbs and veins), the
fishing bobber (type 17, entry 35591, the source of open-water fishing loot)
and fishing pools (type 25); doors, signs and traps are left out.
"""

import argparse
import datetime
import sqlite3
import sys

LOOTABLE_OBJECT_TYPES = (3, 17, 25)


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_names(conn, table, where=""):
    names = {}
    rows = conn.execute(
        f"select entry, patch, name from {table} {where} order by entry, patch")
    for entry, _patch, name in rows:
        if name:
            names[entry] = name.strip()   # later patch rows overwrite earlier ones
    return names


def write_table(out, var, names, comment):
    out.write(f"-- {comment}\n")
    out.write(f"{var} = {{\n")
    for entry in sorted(names):
        out.write(f"[{entry}]={lua_string(names[entry])},\n")
    out.write("}\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vmangos", required=True, help="path to mangos.sqlite")
    ap.add_argument("-o", "--output", default="NameData.lua")
    args = ap.parse_args()

    conn = sqlite3.connect(args.vmangos)
    creatures = read_names(conn, "creature_template")
    objects = read_names(
        conn, "gameobject_template",
        "where type in (%s)" % ",".join(str(t) for t in LOOTABLE_OBJECT_TYPES))

    with open(args.output, "w", encoding="utf-8") as out:
        out.write("-- Generated by tools/build_names.py on %s from the vmangos world\n"
                  "-- database (vanilla 1.12). Do not edit by hand; regenerate.\n"
                  "-- Forever-new creatures and objects are not in here; the addon learns\n"
                  "-- those in play. See the tool's header for the sources.\n\n"
                  % datetime.date.today().isoformat())
        write_table(out, "UlSource.NPCNames", creatures,
                    "NPC ID -> name, %d creatures" % len(creatures))
        write_table(out, "UlSource.ObjectNames", objects,
                    "game object ID -> name, %d chests, nodes and fishing pools" % len(objects))
        fishing = read_names(conn, "gameobject_template", "where type in (17, 25)")
        out.write("-- game object IDs whose loot is fishing: the bobber and every pool, %d objects\n" % len(fishing))
        out.write("UlSource.FishingObjects = {\n")
        for entry in sorted(fishing):
            out.write("[%d]=true,\n" % entry)
        out.write("}\n")
    print(f"{args.output}: {len(creatures)} creatures, {len(objects)} objects", file=sys.stderr)


if __name__ == "__main__":
    main()
